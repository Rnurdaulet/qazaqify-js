import { describe, expect, it } from "vitest";
import { words } from "../src/index.js";

describe("words", () => {
  it("matches Go golden integers", () => {
    const cases: Array<[number | bigint, string]> = [
      [0, "нөл"],
      [1, "бір"],
      [2, "екі"],
      [10, "он"],
      [11, "он бір"],
      [12, "он екі"],
      [20, "жиырма"],
      [21, "жиырма бір"],
      [42, "қырық екі"],
      [99, "тоқсан тоғыз"],
      [100, "жүз"],
      [101, "жүз бір"],
      [110, "жүз он"],
      [200, "екі жүз"],
      [215, "екі жүз он бес"],
      [245, "екі жүз қырық бес"],
      [1000, "мың"],
      [1001, "мың бір"],
      [2000, "екі мың"],
      [4515, "төрт мың бес жүз он бес"],
      [53241, "елу үш мың екі жүз қырық бір"],
      [100000, "жүз мың"],
      [1_000_000, "бір миллион"],
      [1_000_001, "бір миллион бір"],
      [1_001_000, "бір миллион мың"],
      [2_000_000, "екі миллион"],
      [8691705, "сегіз миллион алты жүз тоқсан бір мың жеті жүз бес"],
      [1_000_000_000, "бір миллиард"],
      [1_000_000_000_000, "бір триллион"],
      [-1, "минус бір"],
      [-100, "минус жүз"],
      [
        -9223372036854775808n,
        "минус тоғыз квинтиллион екі жүз жиырма үш квадриллион үш жүз жетпіс екі триллион отыз алты миллиард сегіз жүз елу төрт миллион жеті жүз жетпіс бес мың сегіз жүз сегіз",
      ],
    ];
    for (const [n, want] of cases) {
      expect(words(n), `words(${n})`).toBe(want);
    }
  });
});
